//! 界面文案国际化(同 pointtofixcraft 方案):中文 / English / Deutsch / 日本語。
//!
//! 所有用户可见文案集中在 [`Strings`],`Lang::strings()` 按当前语言返回静态表。
//! 带 `{}` 的模板用 [`fill`] 顺序填充参数。

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Zh,
    En,
    De,
    Ja,
}

impl Lang {
    pub const ALL: [Lang; 4] = [Lang::Zh, Lang::En, Lang::De, Lang::Ja];

    /// 语言自身的名称(语言选择器里使用,不随当前语言变化)
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::Zh => "中文",
            Lang::En => "English",
            Lang::De => "Deutsch",
            Lang::Ja => "日本語",
        }
    }

    /// 持久化到 config.toml 的短代码
    pub fn code(self) -> &'static str {
        match self {
            Lang::Zh => "zh",
            Lang::En => "en",
            Lang::De => "de",
            Lang::Ja => "ja",
        }
    }

    pub fn from_code(code: &str) -> Option<Lang> {
        match code {
            "zh" => Some(Lang::Zh),
            "en" => Some(Lang::En),
            "de" => Some(Lang::De),
            "ja" => Some(Lang::Ja),
            _ => None,
        }
    }

    /// 首次启动跟随系统 UI 语言;不在四种语言内时用英语
    pub fn detect() -> Lang {
        // GetUserDefaultUILanguage 返回 LANGID,低 10 位是主语言 ID
        let primary =
            unsafe { windows::Win32::Globalization::GetUserDefaultUILanguage() } as u32 & 0x3FF;
        match primary {
            0x04 => Lang::Zh, // LANG_CHINESE
            0x07 => Lang::De, // LANG_GERMAN
            0x11 => Lang::Ja, // LANG_JAPANESE
            _ => Lang::En,
        }
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Lang::Zh => &ZH,
            Lang::En => &EN,
            Lang::De => &DE,
            Lang::Ja => &JA,
        }
    }
}

/// 依次把模板里的 `{}` 替换成参数(多余的参数忽略)
pub fn fill(template: &str, args: &[&str]) -> String {
    let mut out = String::with_capacity(template.len() + 32);
    let mut rest = template;
    for arg in args {
        match rest.find("{}") {
            Some(i) => {
                out.push_str(&rest[..i]);
                out.push_str(arg);
                rest = &rest[i + 2..];
            }
            None => break,
        }
    }
    out.push_str(rest);
    out
}

